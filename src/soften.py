_REPL_RE = re.compile("|".join(re.escape(a) for a, _ in REPL))
_REPL_MAP = dict(REPL)
_SENT = re.compile(r"(?<=[.!?。])\s+|(?<=다\.)|(?<=요\.)")


def soften(text):
    if not isinstance(text, str) or not re.search(r"[가-힣]", text):
        return text
    parts = re.split(r"(?<=[.!?])\s+", text)
    out = []
    for p in parts:
        if NO_NEED.search(p):  # '신고·스티커 필요 없음'은 이제 맞지 않는 안내라 뺀다
            continue
        if KEEP.search(p) and not OURS.search(p):
            out.append(p)
            continue
        if DROP.search(p):
            continue
        out.append(_REPL_RE.sub(lambda m: _REPL_MAP[m.group(0)], p))
    return " ".join(out).strip()


def _empty(x):
    return x == "" or (isinstance(x, (tuple, list)) and len(x) > 0 and any(isinstance(v, str) and v == "" for v in x))


def walk(obj):
    """문자열·리스트·튜플·딕셔너리를 돌며 soften 을 적용한다. 리스트 안에서 비게 된 항목은 뺀다."""
    if isinstance(obj, str):
        return soften(obj)
    if isinstance(obj, tuple):
        return tuple(walk(v) for v in obj)
    if isinstance(obj, list):
        res = [walk(v) for v in obj]
        return [v for v in res if not _empty(v)]
    if isinstance(obj, dict):
        return {k: walk(v) for k, v in obj.items()}
    return obj


FORBIDDEN = re.compile(r"수거|가져가|가져갑|실어|싣|적재|운반|수집|처분|트럭|집게차|차량|폐기물 처리")


def leftovers(text):
    """점검용: 공공 절차 문장을 뺀 나머지에서 남은 표현을 찾는다."""
    found = []
    for p in re.split(r"(?<=[.!?])\s+|\n", text):
        if KEEP.search(p) and not OURS.search(p):
            continue
        for m in FORBIDDEN.finditer(p):
            found.append((m.group(0), p.strip()[:80]))
    return found
