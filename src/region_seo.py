COPY = {**SL.SEO, **GG.SEO}


def _h(s, n):
    return int(hashlib.md5(s.encode("utf-8")).hexdigest(), 16) % n


def get(slug):
    return COPY.get(slug)


def pick(slug, key, options):
    """지역마다 다른 문형을 고른다. 같은 권역에서 이웃한 지역끼리 겹치지 않게 순번을 돌린다."""
    return options[_h(slug + key, len(options))]


def missing():
    return [r["slug"] for r in LD.REGIONS if r["slug"] not in COPY]


def lead(r):
    c = get(r["slug"])
    return c["lead"] if c else ""


